import {test,expect} from '@playwright/test';
test('catalog to policy to held-out evaluation and report export',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 const email=`e2e-${Date.now()}@test.example`;
 await page.goto('/dashboard');
 await page.getByRole('button',{name:'Sign in',exact:true}).first().click();
 await page.getByRole('button',{name:'New researcher? Create an account'}).click();
 await page.getByLabel('Display name').fill('E2E Researcher');
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Password',{exact:true}).fill('e2e-test-password-123');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await page.getByRole('link',{name:'Product catalog',exact:true}).click();
 await page.getByLabel('Catalog name',{exact:true}).fill('Browser test catalog');
 await page.getByRole('button',{name:'Save catalog',exact:true}).click();
 await expect(page.getByRole('button',{name:/Browser test catalog/})).toBeVisible();
 await page.getByRole('link',{name:'Market scenarios',exact:true}).click();
 await page.getByRole('combobox',{name:'Catalog',exact:true}).selectOption({index:1});
 await page.getByLabel('Scenario name',{exact:true}).fill('Browser test scenario');
 await page.getByLabel('Episode horizon',{exact:true}).fill('6');
 await page.getByRole('button',{name:'Save new scenario'}).click();
 await expect(page.getByRole('button',{name:/Browser test scenario/})).toBeVisible();
 await page.getByRole('link',{name:/^Training studio/}).click();
 await page.getByRole('combobox',{name:'Scenario',exact:true}).selectOption({index:1});
 await page.getByLabel('Experiment name',{exact:true}).fill('Browser MAPPO');
 await page.getByLabel('Training episodes',{exact:true}).fill('2');
 await page.getByLabel('PPO update epochs',{exact:true}).fill('1');
 await page.getByRole('button',{name:'Create experiment & train'}).click();
 await expect(page.locator('.job-monitor .status-badge')).toHaveText('completed',{timeout:60000});
 await page.getByRole('link',{name:'Robustness suite',exact:true}).click();
 await expect(page.getByRole('heading',{level:1})).toHaveText('Robustness suite');
 await page.getByRole('combobox',{name:'Scenario',exact:true}).selectOption({index:1});
 await expect(page.getByRole('combobox',{name:'Scenario',exact:true})).not.toHaveValue('');
 await page.getByRole('combobox',{name:'Policy',exact:true}).selectOption({index:1});
 await expect(page.getByRole('combobox',{name:'Scenario',exact:true})).not.toHaveValue('');
 await page.getByLabel('Evaluation episodes',{exact:true}).fill('2');
 await expect(page.getByRole('combobox',{name:'Scenario',exact:true})).not.toHaveValue('');
 await page.getByRole('button',{name:'Run evaluation',exact:true}).click();
 await expect(page.locator('.job-monitor .status-badge')).toHaveText('completed',{timeout:60000});
 await page.getByRole('button',{name:/Held-out evaluation.*evaluation/}).click();
 await expect(page.getByRole('heading',{name:'Measured evaluation results'})).toBeVisible();
 await page.getByRole('link',{name:'Reports & exports',exact:true}).click();
 await page.getByRole('combobox',{name:'Evaluation',exact:true}).selectOption({index:1});
 await page.getByRole('button',{name:'Create report',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Report: Held-out evaluation'})).toBeVisible();
 const downloaded=page.waitForEvent('download');await page.getByRole('button',{name:'JSON',exact:true}).click();
 expect((await downloaded).suggestedFilename()).toMatch(/\.json$/);
 await page.goto('/dashboard');
 await expect(page.getByText('Browser MAPPO',{exact:true})).toBeVisible();
 await expect(page.locator('.dashboard-session time')).toContainText(/January|February|March|April|May|June|July|August|September|October|November|December/);
 await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await expect(page.getByRole('button',{name:'Open navigation'})).toBeVisible();
 await page.getByRole('button',{name:'Open navigation'}).click();
 await page.getByRole('link',{name:'Policy registry',exact:true}).click();
 await expect(page.getByRole('heading',{level:1})).toHaveText('Policy registry');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/policies-mobile.png',fullPage:true});
 await page.goto('/dashboard');
 await page.getByRole('button',{name:'Logout',exact:true}).click();
 await expect(page.getByRole('button',{name:'Login',exact:true})).toBeVisible();
 await expect(page.getByText('Browser MAPPO',{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Login',exact:true}).click();
 const login=page.getByRole('dialog',{name:'Research account'});
 await login.getByLabel('Email',{exact:true}).fill(email);
 await login.getByLabel('Password',{exact:true}).fill('e2e-test-password-123');
 await login.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByRole('button',{name:'Logout',exact:true})).toBeVisible();
 await expect(page.getByText('Browser MAPPO',{exact:true})).toBeVisible();
 expect(errors).toEqual([]);
});
